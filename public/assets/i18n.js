  let currentLang = "sw";
  const langListeners = [];

  function getNested(obj, path) {
    return path.split(".").reduce((o, k) => (o && o[k] != null ? o[k] : null), obj);
  }

  function interpolate(str, params) {
    if (!params || typeof str !== "string") return str;
    return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? String(params[k]) : `{${k}}`));
  }

  function t(key, params) {
    const raw = getNested(MESSAGES[currentLang], key) ?? getNested(MESSAGES.en, key);
    if (raw == null) return key;
    return interpolate(String(raw), params);
  }

  function getLang() {
    return currentLang;
  }

  function setLang(lang) {
    if (!MESSAGES[lang]) lang = "sw";
    currentLang = lang;
    try {
      localStorage.setItem("tz_lang", lang);
    } catch (_) {}
    document.documentElement.lang = lang === "sw" ? "sw" : "en";
    applyDataI18n();
    langListeners.forEach((fn) => {
      try {
        fn(lang);
      } catch (_) {}
    });
    return lang;
  }

  function initLang() {
    let saved = "sw";
    try {
      saved = localStorage.getItem("tz_lang") || "sw";
    } catch (_) {}
    setLang(MESSAGES[saved] ? saved : "sw");
    return currentLang;
  }

  function onLangChange(fn) {
    if (typeof fn === "function") langListeners.push(fn);
  }

  function applyDataI18n(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    const titleKey = document.querySelector("title[data-i18n]");
    if (titleKey) titleKey.textContent = t(titleKey.getAttribute("data-i18n"));
    const metaDesc = document.querySelector('meta[name="description"][data-i18n]');
    if (metaDesc) metaDesc.setAttribute("content", t(metaDesc.getAttribute("data-i18n")));
  }

  function roleLabel(role) {
    return t("roles." + (role || "shopper")) || role;
  }

  window.TZI18n = { t, getLang, setLang, initLang, onLangChange, applyDataI18n, roleLabel, MESSAGES };
